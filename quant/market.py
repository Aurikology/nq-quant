"""Historical NQ bars: fetch, cache, load.

Two sources. Yahoo's chart endpoint (`NQ=F`, the continuous front month) is free and needs no key,
but caps history by interval: 1m for about 7 days, 5m and 15m for 60 days. Every fetch is merged
into `data/market/<symbol>_<interval>.csv`, so the cache only grows and a sample built from weekly
fetches gets longer than any single request allows. The second source is any CSV with
time/open/high/low/close columns, such as a TradingView chart export of `CME_MINI:NQ1!`, which is
the way to backtest years instead of weeks.

The cache is gitignored: it is vendor data, and it is regenerated by one command.
"""

from __future__ import annotations

import json
import time as _time
import urllib.request
from pathlib import Path

import pandas as pd

from .config import DATA

MARKET = DATA / "market"
YAHOO = "https://query1.finance.yahoo.com/v8/finance/chart/{symbol}?interval={interval}&range={range}&includePrePost=true"
YAHOO_SPAN = "https://query1.finance.yahoo.com/v8/finance/chart/{symbol}?interval={interval}&period1={p1}&period2={p2}&includePrePost=true"
MAX_RANGE = {"1m": "7d", "2m": "60d", "5m": "60d", "15m": "60d", "30m": "60d", "60m": "730d", "1h": "730d"}
BAR_SECONDS = {"1m": 60, "2m": 120, "5m": 300, "15m": 900, "30m": 1800, "60m": 3600, "1h": 3600}
COLUMNS = ["open", "high", "low", "close", "volume"]


def cache_path(symbol: str, interval: str, root: Path = MARKET) -> Path:
    return root / f"{symbol.replace('=', '').replace('!', '')}_{interval}.csv"


def _chart(url: str) -> pd.DataFrame:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (slash-quant)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        res = json.load(r)["chart"]["result"][0]
    q = res["indicators"]["quote"][0]
    return pd.DataFrame({c: q[c] for c in COLUMNS}, index=pd.to_datetime(res.get("timestamp", []), unit="s", utc=True))


def fetch_yahoo(symbol: str = "NQ=F", interval: str = "5m") -> pd.DataFrame:
    if interval == "1m":
        # 1m is served for the last ~30 days, but at most 7 days per request: walk it in chunks.
        now = int(_time.time())
        parts = [_chart(YAHOO_SPAN.format(symbol=symbol, interval=interval, p1=p1, p2=min(p1 + 7 * 86400, now)))
                 for p1 in range(now - 29 * 86400, now, 7 * 86400)]
        df = pd.concat(parts)
        df = df[~df.index.duplicated(keep="last")].sort_index()
    else:
        df = _chart(YAHOO.format(symbol=symbol, interval=interval, range=MAX_RANGE[interval]))
    df = df.dropna(subset=["open", "high", "low", "close"])
    # Yahoo appends the live quote as an off-grid row (e.g. 22:34:52 on a 5m series). Not a bar.
    df = df[df.index.asi8 % (BAR_SECONDS[interval] * 10**9) == 0]
    # The newest bar is still forming. A backtest that sees it would see the future.
    still_open = df.index + pd.Timedelta(seconds=BAR_SECONDS[interval]) > pd.Timestamp(_time.time(), unit="s", tz="UTC")
    return df[~still_open]


def update_cache(symbol: str = "NQ=F", interval: str = "5m", root: Path = MARKET) -> tuple[Path, int, int]:
    """Fetch and merge into the cache. Returns (path, rows before, rows after)."""
    path = cache_path(symbol, interval, root)
    fresh = fetch_yahoo(symbol, interval)
    old = read_csv(path, tz="UTC") if path.exists() else fresh.iloc[0:0]
    old = old[old.index.asi8 % (BAR_SECONDS[interval] * 10**9) == 0]
    merged = pd.concat([old, fresh])
    merged = merged[~merged.index.duplicated(keep="last")].sort_index()
    path.parent.mkdir(parents=True, exist_ok=True)
    out = merged.copy()
    out.index = out.index.tz_convert("UTC").strftime("%Y-%m-%dT%H:%M:%SZ")
    out.index.name = "time"
    out.to_csv(path)
    return path, len(old), len(merged)


def read_csv(path: Path, tz: str = "America/Toronto") -> pd.DataFrame:
    """Load bars from any CSV with a time column and OHLC columns (case-insensitive).

    Time may be unix seconds (TradingView's default export) or ISO strings with an offset.
    """
    raw = pd.read_csv(path)
    raw.columns = [c.strip().lower() for c in raw.columns]
    t = raw["time"]
    idx = pd.to_datetime(t, unit="s", utc=True) if pd.api.types.is_numeric_dtype(t) else pd.to_datetime(t, utc=True)
    df = raw.set_index(idx)
    if "volume" not in df.columns:
        df["volume"] = 0
    df = df[COLUMNS].astype(float).sort_index()
    df = df[~df.index.duplicated(keep="last")]
    df.index.name = "time"
    return df.tz_convert(tz)


def infer_interval(df: pd.DataFrame) -> str:
    """The bar size, as the box.timeframe string a plan carries."""
    step = int(pd.Series(df.index).diff().dropna().mode().iloc[0].total_seconds())
    for name, secs in BAR_SECONDS.items():
        if secs == step:
            return "1h" if name == "60m" else name
    raise ValueError(f"bars are {step}s apart; expected one of {sorted(set(BAR_SECONDS.values()))}")
